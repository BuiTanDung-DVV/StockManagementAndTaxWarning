  Widget build(BuildContext context) {
    final path = assets[icon];
    if (path == null) {
      return Icon(
        icon,
        size: size,
        color: color,
        semanticLabel: semanticLabel,
        textDirection: textDirection,
      );
    }
    final theme = IconTheme.of(context);
    final opacity = theme.opacity ?? 1;
    final foreground =
        color ?? theme.color ?? Theme.of(context).colorScheme.onSurface;
    final rendered = AppAssetIcon(
      assetPath: path,
      size: size ?? theme.size ?? 24,
      color: foreground.withValues(alpha: foreground.a * opacity),
      semanticLabel: semanticLabel,
    );
    final direction = textDirection ?? Directionality.of(context);
    return icon!.matchTextDirection && direction == TextDirection.rtl
        ? Transform.flip(flipX: true, child: rendered)
        : rendered;
  }
